// Площадь прямоугольника
export function rectangleArea(a, b) {
    return a * b;
}

// Периметр прямоугольника
export function rectanglePerimeter(a, b) {
    return 2 * (a + b);
}

// Площадь круга
export function circleArea(r) {
    return Math.PI * r * r;
}

// Длина окружности
export function circlePerimeter(r) {
    return 2 * Math.PI * r;
}